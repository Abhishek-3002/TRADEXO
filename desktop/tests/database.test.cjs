test('records append-only customer receipts and calculates paid, part-paid and outstanding balances', async () => {
  const { db, vendor, customer, product } = await createTradingFixture()
  const purchase = db.createPurchaseBillDraft({ vendorId: vendor.id, billNumber: 'RCPT-PB-1', billDate: '2026-04-10', items: [{ productId: product.id, quantity: 10, unitCost: 10 }] })
  db.postPurchaseBill(purchase.id)
  const invoice = db.createSalesInvoiceDraft({ customerId: customer.id, invoiceNumber: 'RCPT-SI-1', invoiceDate: '2026-04-11', items: [{ productId: product.id, quantity: 2, unitPrice: 100 }] })
  assert.throws(() => db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-0', receiptDate: '2026-04-12', amount: 20, paymentMethod: 'cash' }), /Only a posted invoice/)
  db.postSalesInvoice(invoice.id)
  const first = db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-001', receiptDate: '2026-04-12', amount: 50, paymentMethod: 'upi', reference: 'UPI-REF-1' })
  assert.equal(first.payment_status, 'part_paid')
  assert.equal(first.received_amount, 50)
  assert.equal(first.outstanding_amount, 150)
  assert.throws(() => db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-OVER', receiptDate: '2026-04-12', amount: 151, paymentMethod: 'cash' }), /exceeds outstanding/)
  assert.throws(() => db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-BAD', receiptDate: '2026-02-30', amount: 10, paymentMethod: 'cash' }), /valid receipt date/)
  assert.throws(() => db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-ZERO', receiptDate: '2026-04-12', amount: 0, paymentMethod: 'cash' }), /greater than zero/)
  const second = db.recordSalesReceipt({ invoiceId: invoice.id, receiptNumber: 'R-002', receiptDate: '2026-04-13', amount: 150, paymentMethod: 'bank_transfer' })
  assert.equal(second.payment_status, 'paid')
  assert.equal(second.outstanding_amount, 0)
  const saved = db.getSalesInvoice(invoice.id)
  assert.equal(saved.received_amount, 200)
  assert.equal(saved.outstanding_amount, 0)
  assert.equal(saved.payment_status, 'paid')
  assert.equal(db.listSalesInvoices()[0].payment_status, 'paid')
  assert.equal(db.listSalesReceipts(invoice.id).length, 2)
  assert.equal(db.listSalesReceipts()[0].invoice_number, 'RCPT-SI-1')
  assert.equal(db.listSalesReceipts(invoice.id).reduce((sum, receipt) => sum + receipt.amount, 0), 200)
  db.close()
})

test('reverses posted sales and purchase with compensating stock entries, never deleting history', async () => {
  const { db, vendor, customer, product } = await createTradingFixture()
  const purchase = db.createPurchaseBillDraft({ vendorId: vendor.id, billNumber: 'PB-003', billDate: '2026-04-10', items: [{ productId: product.id, quantity: 7, unitCost: 10 }] })
  db.postPurchaseBill(purchase.id)
  const invoice = db.createSalesInvoiceDraft({ customerId: customer.id, invoiceNumber: 'SI-003', invoiceDate: '2026-04-11', items: [{ productId: product.id, quantity: 2, unitPrice: 20 }] })
  db.postSalesInvoice(invoice.id)
  assert.throws(() => db.reversePurchaseBill(purchase.id, 'Supplier return'), /already been sold or consumed/)
  db.reverseSalesInvoice(invoice.id, 'Wrong customer')
  assert.equal(db.getProductStock(product.id).current_stock, 7)
  db.reversePurchaseBill(purchase.id, 'Supplier return')
  assert.equal(db.getProductStock(product.id).current_stock, 0)
  assert.equal(db.listStockMovements().length, 4)
  assert.equal(db.getSalesInvoice(invoice.id).status, 'reversed')
  assert.equal(db.getPurchaseBill(purchase.id).status, 'reversed')
  assert.throws(() => db.reverseSalesInvoice(invoice.id, 'Again'), /Only a posted invoice/)
  assert.throws(() => db.reversePurchaseBill(purchase.id, 'Again'), /Only a posted purchase/)
  db.close()
})


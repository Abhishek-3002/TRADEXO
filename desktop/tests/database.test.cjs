test('allows the same SKU in different companies but prevents duplicates within one company', async () => {
  const db = await openLocalDatabase()
  const first = db.getCurrentCompany()
  db.createProduct({ name: 'Item A', sku: 'SHARED-01', sellingPrice: 10, openingStock: 1 })
  assert.throws(() => db.createProduct({ name: 'Duplicate in A', sku: 'SHARED-01' }))
  const second = db.createCompany({ businessName: 'Another Company' })
  db.setActiveCompany(second.id)
  assert.doesNotThrow(() => db.createProduct({ name: 'Item B', sku: 'SHARED-01', sellingPrice: 20, openingStock: 2 }))
  db.setActiveCompany(first.id)
  assert.equal(db.listProducts().length, 1)
  db.close()
})

test('refuses to save a disk database without an encryption provider', async () => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'bizora-no-plain-'))
  const file = path.join(folder, 'bizora.sqlite')
  await assert.rejects(() => openLocalDatabase(file), /encryption is required/)
  assert.equal(fs.existsSync(file), false)
  fs.rmSync(folder, { recursive: true, force: true })
})

test('creates encrypted backup and restores the saved company data', async () => {
  const source = await openLocalDatabase(null, testEncryption)
  source.createCustomer({ name: 'Customer From Backup' })
  const backup = source.createEncryptedBackup()
  assert.equal(backup.subarray(0, Buffer.byteLength('BIZORA_DB_ENC_V1\\n')).toString(), 'BIZORA_DB_ENC_V1\\n')
  source.close()

  const target = await openLocalDatabase(null, testEncryption)
  target.createCustomer({ name: 'Current Local Customer' })
  const result = target.restoreEncryptedBackup(backup)
  assert.equal(result.restored, true)
  assert.equal(target.listCustomers().length, 1)
  assert.equal(target.listCustomers()[0].name, 'Customer From Backup')
  assert.ok(target.getSummary().audit_events >= 2)
  target.close()
})

test('rejects a damaged backup without replacing current data', async () => {
  const db = await openLocalDatabase(null, testEncryption)
  db.createCustomer({ name: 'Keep This Customer' })
  const backup = db.createEncryptedBackup()
  backup[backup.length - 1] ^= 0xff
  assert.throws(() => db.restoreEncryptedBackup(backup), /Backup restore failed/)
  assert.equal(db.listCustomers()[0].name, 'Keep This Customer')
  db.close()
})

test('creates company-scoped financial years, prevents overlaps and allows one active year', async () => {
  const db = await openLocalDatabase()
  const first = db.getCurrentCompany()
  const fy = db.createFinancialYear({ label: '2026-27', startDate: '2026-04-01', endDate: '2027-03-31' })
  assert.equal(fy.status, 'inactive')
  assert.equal(db.listFinancialYears().length, 1)
  assert.throws(() => db.createFinancialYear({ label: 'FY overlap', startDate: '2026-12-01', endDate: '2027-11-30' }), /overlaps/)
  assert.throws(() => db.createFinancialYear({ label: 'Bad dates', startDate: '2027-04-01', endDate: '2027-03-31' }), /on or before/)
  assert.throws(() => db.createFinancialYear({ label: 'Invalid date', startDate: '2026-02-30', endDate: '2026-03-31' }), /valid dates/)
  const second = db.createFinancialYear({ label: '2027-28', startDate: '2027-04-01', endDate: '2028-03-31' })
  db.setActiveFinancialYear(fy.id)
  assert.equal(db.listFinancialYears().find(x => x.id === fy.id).status, 'active')
  db.setActiveFinancialYear(second.id)
  assert.equal(db.listFinancialYears().filter(x => x.status === 'active').length, 1)
  assert.equal(db.listFinancialYears().find(x => x.id === second.id).status, 'active')
  const companyB = db.createCompany({ businessName: 'Separate FY Company' })
  db.setActiveCompany(companyB.id)
  assert.equal(db.listFinancialYears().length, 0)
  db.setActiveCompany(first.id)
  assert.equal(db.listFinancialYears().length, 2)
  db.close()
})

test('keeps GST tax settings company-scoped and validates GSTIN ownership', async () => {
  const db = await openLocalDatabase()
  const first = db.getCurrentCompany()
  const registration = db.addCompanyGstin({ gstin: '08ABCDE1234F1Z5', label: 'Rajasthan' })
  assert.throws(() => db.saveCompanyTaxSettings({ gstEnabled: true, defaultTaxMode: 'exclusive' }), /Select a GSTIN/)
  assert.throws(() => db.saveCompanyTaxSettings({ gstEnabled: true, defaultTaxMode: 'none', defaultGstinId: registration.id }), /inclusive or exclusive/)
  const saved = db.saveCompanyTaxSettings({ gstEnabled: true, defaultTaxMode: 'exclusive', placeOfSupplyStateCode: '08', defaultGstinId: registration.id })
  assert.equal(saved.gst_enabled, 1)
  assert.equal(saved.default_gstin_id, registration.id)
  const second = db.createCompany({ businessName: 'Tax Settings Company' })
  db.setActiveCompany(second.id)
  assert.equal(db.getCompanyTaxSettings().gst_enabled, 0)
  assert.throws(() => db.saveCompanyTaxSettings({ gstEnabled: true, defaultTaxMode: 'inclusive', defaultGstinId: registration.id }), /does not belong/)
  db.setActiveCompany(first.id)
  assert.equal(db.getCompanyTaxSettings().default_tax_mode, 'exclusive')
  assert.throws(() => db.saveCompanyTaxSettings({ gstEnabled: false, defaultTaxMode: 'none', placeOfSupplyStateCode: 'ABC' }), /two digits/)
  db.close()
})

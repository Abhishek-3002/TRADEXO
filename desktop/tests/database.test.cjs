test('creates encrypted backup and restores the saved company data', async () => {
  const source = await openLocalDatabase(null, testEncryption)
  source.createCustomer({ name: 'Customer From Backup' })
  const gstin = source.addCompanyGstin({ gstin: '08ABCDE1234F1Z5', label: 'Rajasthan' })
  const customer = source.createCustomer({ name: 'Invoice Customer' })
  const product = source.createProduct({ name: 'Backup Product', sku: 'BK-01', sellingPrice: 20, openingStock: 0 })
  const vendor = source.createVendor({ name: 'Backup Supplier', phone: '9876543210' })
  const year = source.createFinancialYear({ label: '2026-27', startDate: '2026-04-01', endDate: '2027-03-31' })
  source.setActiveFinancialYear(year.id)
  source.saveCompanyTaxSettings({ gstEnabled: true, defaultTaxMode: 'exclusive', placeOfSupplyStateCode: '08', defaultGstinId: gstin.id })
  const purchase = source.createPurchaseBillDraft({ vendorId: vendor.id, billNumber: 'SUP-001', billDate: '2026-05-01', items: [{ productId: product.id, quantity: 5, unitCost: 8 }] })
  source.postPurchaseBill(purchase.id)
  source.createSalesInvoiceDraft({ customerId: customer.id, invoiceNumber: 'INV-001', invoiceDate: '2026-05-02', items: [{ productId: product.id, quantity: 2, unitPrice: 20 }] })
  const backup = source.createEncryptedBackup()
  assert.equal(backup.subarray(0, Buffer.byteLength('BIZORA_DB_ENC_V1\\n')).toString(), 'BIZORA_DB_ENC_V1\\n')
  source.close()

  const target = await openLocalDatabase(null, testEncryption)
  target.createCustomer({ name: 'Current Local Customer' })
  const result = target.restoreEncryptedBackup(backup)
  assert.equal(result.restored, true)
  assert.equal(target.listCustomers().length, 2)
  assert.ok(target.listCustomers().some(item => item.name === 'Customer From Backup'))
  assert.equal(target.listFinancialYears()[0].status, 'active')
  assert.equal(target.getCompanyTaxSettings().default_tax_mode, 'exclusive')
  assert.equal(target.getCompanyTaxSettings().place_of_supply_state_code, '08')
  assert.equal(target.listVendors()[0].name, 'Backup Supplier')
  assert.equal(target.listPurchaseBills()[0].status, 'posted')
  assert.equal(target.listSalesInvoices()[0].status, 'draft')
  assert.equal(target.getProductStock(product.id).current_stock, 5)
  assert.equal(target.listStockMovements().length, 1)
  assert.ok(target.getSummary().audit_events >= 2)
  target.close()
})

